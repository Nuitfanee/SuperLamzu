def flash_source(address):
    for source, run, size in COPIES:
        if run <= address < run + size:
            return source + address - run
    return address


def runtime(address):
    for source, run, size in COPIES:
        if source <= address < source + size:
            return run + address - source
    return address


@dataclass(frozen=True)
class StockTarget:
    name: str
    source: Path
    base: int
    span: int
    defined_bytes: int
    initial_sp: int
    reset: int

    def inspect(self):
        from superlamzu.hexfile import Image
        image = Image(self.source)
        actual = (image.base, image.end - image.base, len(image.mem),
                  image.u32(image.base), image.u32(image.base + 4), image.entry)
        expected = (self.base, self.span, self.defined_bytes,
                    self.initial_sp, self.reset, self.reset)
        if actual != expected:
            raise ValueError(f'{self.name}: stock sparse identity changed: {actual}')
        return dict(target=self.name, version=VERSION, source=str(self.source),
                    base=self.base, span_bytes=self.span, defined_bytes=self.defined_bytes,
                    gap_bytes=self.span-self.defined_bytes, initial_sp=self.initial_sp,
                    reset_vector=self.reset, flash_available=False)


